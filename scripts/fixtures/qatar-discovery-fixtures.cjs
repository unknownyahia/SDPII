function buildActionLinks(id, name, area, primaryCategory) {
  return {
    mapsQuery: `${name}, ${area}, Qatar`,
    shareSlug: `spots://places/${id}`,
    primaryAction:
      primaryCategory === 'familyDining' || primaryCategory === 'casualDining'
        ? 'reserve'
        : primaryCategory === 'culture'
          ? 'details'
          : 'directions',
  };
}

